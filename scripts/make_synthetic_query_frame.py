#!/usr/bin/env python3
"""
Build the synthetic query-frame bundle a fresh clone localizes with.

The real bundle (web/public/query-frames/) is photographs of a real place and
is never committed, so a fresh clone had no way to reach the localize round
trip from the UI. This writes the committed stand-in, under
web/public/query-frames-synthetic/:

- one JPEG that is a drawn card, not a photograph, and says so in its pixels,
  in its file name and in its JPEG comment;
- a manifest whose anchor is copied from the venue's own anchor config
  (bridges/web_bridge/tests/frame_anchors_fountain.json), so it claims no
  location that file does not already declare.

The page falls back to this bundle only when no real one is installed. It runs
the same path a real frame does: VPS search, the blob lane, the vps query and
response, and the pose the service computes. Nothing is canned. What it cannot
do is be matched against a map; a real VPS given this card would rightly fail
it, and the demo's mock VPS ignores pixels either way (ar_demo/README.md).

    scripts/make_synthetic_query_frame.py          # rewrite the bundle
    scripts/make_synthetic_query_frame.py --check  # exit 1 if it would change
"""
import argparse
import io
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
ANCHORS = REPO / "bridges" / "web_bridge" / "tests" / "frame_anchors_fountain.json"
DEST = REPO / "web" / "public" / "query-frames-synthetic"
FRAME = "synthetic-query-frame-0001.jpg"
LABEL = "SYNTHETIC query frame, not a photograph"

# The real frames are stored 720x960, sideways, and the page's preview rotates
# them upright with CSS (web/src/style.css). The card is drawn upright and
# stored the same way so the preview shows it the right way up.
UPRIGHT = (960, 720)


def venue_anchor() -> tuple[str, dict]:
    anchors = json.loads(ANCHORS.read_text())
    if len(anchors) != 1:
        sys.exit(f"{ANCHORS}: expected one venue anchor, found {len(anchors)}")
    (fqn, a), = anchors.items()
    return fqn, a


def manifest(fqn: str, a: dict) -> dict:
    return {
        "$comment": "Generated by scripts/make_synthetic_query_frame.py; anchor copied "
                    "from bridges/web_bridge/tests/frame_anchors_fountain.json. Do not edit.",
        "synthetic": True,
        "label": LABEL,
        "mapFqn": fqn,
        "anchor": {"lat_deg": a["latitude"], "lon_deg": a["longitude"], "alt_m": a["height"]},
        "frames": [FRAME],
    }


def card(fqn: str, a: dict) -> bytes:
    # Here, not at the top: --check (run by the test suite) needs no imaging.
    from PIL import Image, ImageDraw, ImageFont

    w, h = UPRIGHT
    im = Image.new("RGB", UPRIGHT, (24, 28, 36))
    d = ImageDraw.Draw(im)
    # A test-card grid, so the JPEG is a realistic size for the blob lane
    # rather than a few hundred bytes of flat colour.
    for x in range(0, w, 40):
        for y in range(0, h, 40):
            shade = ((x // 40) * 37 + (y // 40) * 53) % 96
            d.rectangle([x, y, x + 39, y + 39], fill=(32 + shade, 40 + shade // 2, 56 + shade))
            d.line([x, y, x + 39, y + 39], fill=(90, 100, 120))
    d.rectangle([40, 180, w - 40, h - 180], fill=(250, 214, 0), outline=(0, 0, 0), width=6)
    big = ImageFont.load_default(size=88)
    small = ImageFont.load_default(size=26)
    d.text((w // 2, 270), "SYNTHETIC", font=big, fill=(0, 0, 0), anchor="mm")
    d.text((w // 2, 345), "query frame, not a photograph", font=small, fill=(0, 0, 0), anchor="mm")
    d.text((w // 2, 390), f"venue anchor {fqn}", font=small, fill=(0, 0, 0), anchor="mm")
    d.text((w // 2, 430), f"{a['latitude']:.6f}, {a['longitude']:.6f}", font=small,
           fill=(0, 0, 0), anchor="mm")
    d.text((w // 2, 500), "no VPS can match this; see ar_demo/README.md", font=small,
           fill=(0, 0, 0), anchor="mm")
    stored = im.transpose(Image.Transpose.ROTATE_270)
    out = io.BytesIO()
    stored.save(out, "JPEG", quality=90, comment=LABEL.encode())
    return out.getvalue()


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true",
                    help="report whether the committed manifest matches the anchor config")
    args = ap.parse_args()

    fqn, a = venue_anchor()
    text = json.dumps(manifest(fqn, a), indent=2) + "\n"
    target = DEST / "manifest.json"
    if args.check:
        current = target.read_text() if target.is_file() else ""
        if current != text:
            print(f"{target} is stale against {ANCHORS}; rerun {Path(__file__).name}")
            return 1
        return 0

    DEST.mkdir(parents=True, exist_ok=True)
    target.write_text(text)
    (DEST / FRAME).write_bytes(card(fqn, a))
    print(f"wrote {target} and {DEST / FRAME}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
