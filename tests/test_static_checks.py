class MermaidDiagramsParse(unittest.TestCase):
    """
    Mermaid blocks that GitHub can actually render.

    A diagram that fails to parse does not degrade — GitHub replaces the whole
    block with "Unable to render rich display", so a README's most useful part
    silently becomes an error box. Nothing in the normal test run touches
    markdown, so it stays broken until someone opens the page.

    This is a targeted check, not a parser. It catches the construct that
    actually broke ar_demo/README.md: a semicolon in message or note text.
    Mermaid treats `;` as a statement separator, so `cached; dispose, Depart`
    ends the message at the semicolon and then fails on what follows. The rest
    of the line reads perfectly well to a human, which is what makes it worth a
    test rather than a review note.
    """

    ROOT = pathlib.Path(__file__).resolve().parent.parent
    # cdk.out holds build-cache copies of files that live elsewhere in the tree.
    SKIP = ("node_modules", "cdk.out", "directions")

    def _blocks(self):
        for md in sorted(self.ROOT.rglob("*.md")):
            rel = md.relative_to(self.ROOT)
            if any(part in self.SKIP for part in rel.parts):
                continue
            text = md.read_text(errors="ignore")
            for n, block in enumerate(
                    re.findall(r"```mermaid\n(.*?)```", text, re.S), 1):
                yield rel, n, block

    def test_no_semicolons_in_diagram_text(self):
        found = []
        for rel, n, block in self._blocks():
            for line in block.splitlines():
                stripped = line.strip()
                if not stripped or stripped.startswith("%%"):
                    continue
                # Only the text after the first ':' is message/note content.
                _, sep, text = stripped.partition(":")
                if sep and ";" in text:
                    found.append(f"{rel} (block {n}): {stripped}")
        self.assertEqual(found, [], "semicolons break mermaid parsing:\n  " +
                         "\n  ".join(found))

    def test_every_participant_is_declared(self):
        """
        An undeclared participant still renders, in first-use order rather than
        the order the diagram intends — so the columns silently rearrange.
        """
        problems = []
        for rel, n, block in self._blocks():
            if not block.lstrip().startswith("sequenceDiagram"):
                continue
            declared = set(re.findall(r"^\s*participant\s+(\w+)", block, re.M))
            used = set()
            for a, b in re.findall(r"^\s*(\w+)\s*-+>>?\s*(\w+)\s*:", block, re.M):
                used |= {a, b}
            for note in re.findall(r"^\s*Note over ([\w, ]+):", block, re.M):
                used |= {x.strip() for x in note.split(",")}
            missing = sorted(used - declared)
            if missing:
                problems.append(f"{rel} (block {n}): {', '.join(missing)}")
        self.assertEqual(problems, [], "undeclared mermaid participants:\n  " +
                         "\n  ".join(problems))


class GeneratedTypesIntrospect(unittest.TestCase):
    """Every generated dataclass answers `typing.get_type_hints()`.

    This is the check that replaced an exclusion's apology. idlc annotates a
    nested member with a fully-qualified string --- `'spatialdds_idl18.spatial
    .common.Mat3x3'` --- and imports only `spatial` from the root package, so
    the root name was unbound and `get_type_hints` raised NameError on every
    generated type in both trees, from the 1.7 cutover until 2026-10-18.

    Nothing broke, which is why it lasted: CycloneDDS resolves these
    annotations with its own machinery and never calls `get_type_hints`. But
    `get_type_hints` is how dataclass-based tooling reads a type, so schema
    generators, validators and API frameworks could not introspect these
    bindings at all --- a type system whose Python bindings cannot be read by
    standard means is smaller than it looks.

    Checked over every module of this repository's generated tree and of the
    spec tree it binds to, because the defect was uniform and a spot check
    would have passed on any file idlc happened to emit without a nested
    member. The spec tree is the SDK's (`spatialdds.dds.types`) since the
    adoption retired this repository's `spatialdds_idl18`; the demo tree's
    annotations name it, so it is checked here too.
    """

    def test_every_generated_dataclass_resolves_its_annotations(self):
        import dataclasses
        import importlib
        import pkgutil
        import typing

        self.assertEqual(
            GENERATED_TREES, ["spatialdds_demo_idl18"],
            f"expected the demo's tree alone, found {GENERATED_TREES} "
            f"-- the discovery is broken, not the code")

        checked = 0
        failures = []
        for tree in GENERATED_TREES + ["spatialdds.dds.types"]:
            pkg = importlib.import_module(tree)
            for mod in pkgutil.walk_packages(pkg.__path__, f"{tree}."):
                try:
                    m = importlib.import_module(mod.name)
                except Exception:
                    continue          # optional deps are not this test's business
                for name in dir(m):
                    obj = getattr(m, name)
                    if not (isinstance(obj, type)
                            and dataclasses.is_dataclass(obj)
                            and obj.__module__ == mod.name):
                        continue
                    checked += 1
                    try:
                        typing.get_type_hints(obj)
                    except NameError as e:
                        failures.append(f"{mod.name}.{name}: {e}")
        self.assertEqual(
            failures[:6], [],
            f"{len(failures)} generated dataclass(es) cannot resolve their "
            f"own annotations; first few: {failures[:6]}")
        self.assertGreater(
            checked, 100,
            f"only {checked} dataclasses examined across {GENERATED_TREES} -- "
            f"too few to be the whole of the generated trees, so the walk is "
            f"broken rather than the code clean")
        print(f"\n  get_type_hints: {checked} generated dataclass(es) across "
              f"{len(GENERATED_TREES)} tree(s), all resolvable")
