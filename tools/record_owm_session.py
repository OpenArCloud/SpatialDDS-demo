#!/usr/bin/env python3
"""Record a live session of the Open World Model demo to a typed MCAP.

    python3 tools/record_owm_session.py --seconds 20 \
        --out recordings/owm-littlefield.mcap

This subscribes to the migrated demo's DDS topics with CycloneDDS, the same
way any other consumer does, and writes what arrives. It is a capture, not an
authoring tool: there is no input file, nothing is computed, and the only
thing it adds is the typed envelope -- §3.3.1 topic names as channels, the
flattened 1.8 IDL as `omgidl` schemas, and XCDR2 as the message encoding.

**The bytes are CycloneDDS's, on purpose.** Each sample is re-serialized with
the serializer that put it on the wire, and the gateway that reads this file
back decodes it with an independent pure-Python XCDR2 reader. Two
implementations of the same encoding have to agree about every member of
every record, which is a property no single-implementation test can check --
and the one that found the dead base64 rule in the web binding's own mapping
table. A recorder that borrowed the gateway's encoder would have proved
nothing but self-consistency.

**The IDL is this repository's vendored pin**, `idl/v1.8/`, taken from
SpatialDDS-spec at 9c3e1f2 -- the same commit the validating gateway's own
artifacts are generated from. The flatten convention (preamble, one
`// ---- name ----` banner per file, `#` directives stripped, joined with
newlines) matches the one the web binding's recordings use, because the
reader on the other side parses each schema record as a single translation
unit and that is the form it expects.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
import time
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
if str(REPO) not in sys.path:
    sys.path.insert(0, str(REPO))

from mcap.writer import Writer  # noqa: E402

from spatialdds_demo import typed_transport as tt  # noqa: E402
from spatialdds_demo.qos_profiles import (  # noqa: E402
    MODEL_COMMAND, MODEL_FAST, MODEL_LATCHED)
from spatialdds_demo.topics import (  # noqa: E402
    SCENE, TOPIC_MODEL_COMMAND_V1, TOPIC_MODEL_ENTITY_V1, TOPIC_MODEL_POSE_V1)
from spatialdds_idl18.spatial.owm import (  # noqa: E402
    Entity, ModelCommand, ModelPose)

IDL_DIR = REPO / "idl" / "v1.8"
SPEC_COMMIT = "9c3e1f2"

PREAMBLE = """// Flattened for the MCAP schema payload: includes resolved and
// preprocessor directives removed, so this is a single
// self-contained translation unit. Generated by
// tools/record_owm_session.py; the authoritative sources are the
// SpatialDDS 1.8 idl/ tree vendored in idl/v1.8/.
"""

#: Each recorded type with the closure of its own definition, in dependency
#: order. `owm.idl` includes `core.idl` and `types.idl` and nothing else, so
#: this is the whole closure rather than a convenient subset of it.
CLOSURES: dict[str, list[str]] = {
    "spatial::owm::Entity": ["types.idl", "core.idl", "provisional/owm.idl"],
    "spatial::owm::ModelPose": ["types.idl", "core.idl",
                                "provisional/owm.idl"],
    "spatial::owm::ModelCommand": ["types.idl", "core.idl",
                                   "provisional/owm.idl"],
}

#: Topic, python type, QoS profile name, schema name. One row per lane the
#: demo actually publishes; the relationship lane is absent because
#: `spatial.owm/0.1` carries no relationship type.
LANES = [
    (TOPIC_MODEL_ENTITY_V1, Entity, MODEL_LATCHED, "spatial::owm::Entity"),
    (TOPIC_MODEL_POSE_V1, ModelPose, MODEL_FAST, "spatial::owm::ModelPose"),
    (TOPIC_MODEL_COMMAND_V1, ModelCommand, MODEL_COMMAND,
     "spatial::owm::ModelCommand"),
]


def flatten(files: list[str]) -> bytes:
    """The named IDL files as one translation unit, directives stripped."""
    out = [PREAMBLE]
    for name in files:
        text = (IDL_DIR / name).read_text()
        body = "\n".join(line for line in text.splitlines()
                         if not line.lstrip().startswith("#"))
        out.append(f"\n// ---- {Path(name).name} ----\n{body}")
    return "\n".join(out).encode()


def record(out: Path, seconds: float, domain_id: int) -> dict:
    """Capture every lane for `seconds`, and return the provenance."""
    from cyclonedds.domain import DomainParticipant

    participant = DomainParticipant(domain_id)
    readers = [(topic, tt.make_reader(participant, topic, cls, qos.name), name)
               for topic, cls, qos, name in LANES]

    out.parent.mkdir(parents=True, exist_ok=True)
    counts: dict[str, int] = {topic: 0 for topic, _, _, _ in LANES}
    started = time.time()

    with open(out, "wb") as f:
        writer = Writer(f)
        writer.start()
        schema_ids = {
            name: writer.register_schema(name=name, encoding="omgidl",
                                         data=flatten(files))
            for name, files in CLOSURES.items()
        }
        channel_ids = {
            topic: writer.register_channel(topic=topic, message_encoding="cdr",
                                           schema_id=schema_ids[name])
            for topic, _, _, name in LANES
        }

        deadline = started + seconds
        while time.time() < deadline:
            for topic, reader, _name in readers:
                for sample in tt.take_samples(reader) or []:
                    now = time.time_ns()
                    writer.add_message(
                        channel_id=channel_ids[topic],
                        log_time=now,
                        # The demo stamps every record with the time it was
                        # authored, and that is the publish time. Taking the
                        # capture clock for both would claim this recorder
                        # knows when the sample was written, which it does
                        # not -- it knows when it arrived.
                        publish_time=(sample.stamp.sec * 1_000_000_000
                                      + sample.stamp.nanosec),
                        data=sample.serialize(),
                    )
                    counts[topic] += 1
            time.sleep(0.02)
        writer.finish()

    elapsed = time.time() - started
    return {
        "recording": out.name,
        "sha256": hashlib.sha256(out.read_bytes()).hexdigest(),
        "bytes": out.stat().st_size,
        "captured_utc": time.strftime("%Y-%m-%dT%H:%M:%SZ",
                                      time.gmtime(started)),
        "capture_seconds": round(elapsed, 2),
        "scene": SCENE,
        "dds_domain": domain_id,
        "types": "spatial.owm/0.1 (provisional)",
        "spec_commit": SPEC_COMMIT,
        "idl_source": "idl/v1.8 (vendored from SpatialDDS-spec "
                      f"{SPEC_COMMIT})",
        "message_encoding": "cdr (XCDR2, serialized by CycloneDDS)",
        "schema_encoding": "omgidl",
        "schemas": {name: hashlib.sha256(flatten(files)).hexdigest()
                    for name, files in CLOSURES.items()},
        "samples": counts,
        "recorded_by": "tools/record_owm_session.py",
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__ or "",
                                     formatter_class=argparse
                                     .RawDescriptionHelpFormatter)
    parser.add_argument("--out", type=Path,
                        default=REPO / "recordings" / "owm-littlefield.mcap")
    parser.add_argument("--seconds", type=float, default=20.0)
    parser.add_argument("--domain", type=int, default=0)
    args = parser.parse_args()

    print(f"record: scene {SCENE}, domain {args.domain}, "
          f"{args.seconds:.0f}s")
    for topic, _, _, name in LANES:
        print(f"record: {topic}  <- {name}")
    prov = record(args.out, args.seconds, args.domain)
    side = args.out.with_suffix(".provenance.json")
    side.write_text(json.dumps(prov, indent=2) + "\n")

    total = sum(prov["samples"].values())
    for topic, n in prov["samples"].items():
        print(f"record: {n:5d} samples on {topic}")
    print(f"record: {total} samples, {prov['bytes']} bytes, "
          f"sha256 {prov['sha256'][:16]}")
    print(f"record: provenance {side.relative_to(REPO)}")
    if total == 0:
        print("record: nothing arrived -- is the demo running on this "
              "domain? An empty recording is not evidence.")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
